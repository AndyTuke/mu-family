// Layer-extraction safety net for mu-Clid, part 1: golden renders. Each scenario drives the REAL headless
// PluginProcessor through mu-core's GoldenRender.h and compares a bit-exact fingerprint of the master,
// every rhythm's stem and the MIDI the processor emitted with the one recorded from the unextracted tree
// (tests/golden/mu-clid/<name>/). The frozen inputs (state.xml, scenario.json) live beside the golden; a
// golden changes only through tests/scripts/update-golden.ps1, never in a commit that moves code.
//
// Part 2, the pins that describe behaviour a later stage will move, is ExtractionPinTests.cpp.
//
// Authoring the inputs: state.xml is a real host session saved by the code below, and scenario.json is
// written from the Scenario itself, so neither is hand-edited. Run the test exe with
// MU_GOLDEN_AUTHOR_STATE=1 to rewrite them; the input hash then changes, which is a deliberate update.
// The fixture samples the states name are generated by GoldenTestRig.h at load time.

