    // One scenario: how its frozen state is built (authoring only) and what the render does.
    struct Def
    {
        juce::String name;
        int numStems = 0;
        juce::int64 lengthFrames = 96000;
        double tempoBpm = 120.0;
        double startBeat = 0.0;
        int preparedBlockSize = 1024;   // above the largest scheduled block, so no block is oversize
        std::vector<mu_golden::Schedule> schedules { mu_golden::Schedule::fixed512(), mu_golden::Schedule::ragged() };
        std::function<void(PluginProcessor&)> author;
        std::vector<mu_golden::ScriptedEvent> events;
        juce::String notes;
    };

    PluginProcessor& clid(mu_golden::ScriptContext& c) { return static_cast<PluginProcessor&>(c.proc); }

    // Event helpers: parameter sets and host edits at a block index.
    mu_golden::ScriptedEvent setParamAt(int block, const juce::String& id, float value)
    {
        return { block, "set " + id + " = " + juce::String(value),
                 [id, value](mu_golden::ScriptContext& c) { setParam(c.proc.apvts, id, value); } };
    }

    // A stepped control sequence with the given -100..100 step values.
    void stepped(mu_clid::Rhythm& r, int cs, std::vector<float> v, ControlSequence::Polarity pol = ControlSequence::Polarity::Bipolar)
    {
        auto& seq = r.controlSequences[(size_t) cs];
        seq.mode = ControlSequence::Mode::Stepped;
        seq.polarity = pol;
        seq.stepValues = std::move(v);
    }

    void assign(mu_clid::Rhythm& r, const char* id, const char* src, const char* dest, float depth)
    {
        ModulationAssignment a;
        a.id = id; a.sourceId = src; a.destinationId = dest; a.depth = depth;
        [[maybe_unused]] const bool added = r.modulationMatrix.addAssignment(a);
        jassert(added);
    }

    // The Euclid ring A of rhythm `r`: steps, hits, rotation.
    void ringA(PluginProcessor& p, int r, int steps, int hits, int rot = 0)
    {
        setParam(p.apvts, rp(r, "stepsA"), (float) steps);
        setParam(p.apvts, rp(r, "hitsA"), (float) hits);
        setParam(p.apvts, rp(r, "rotA"), (float) rot);
    }

