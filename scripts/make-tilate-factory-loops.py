"""Renders the mu-Tilate factory loops: short original synthetic drum loops (2 bars of 4/4, 44.1 kHz, 24-bit mono WAV).

Deterministic (fixed seeds), so the files can be regenerated byte-for-byte.
Usage: python scripts/make-tilate-factory-loops.py [output_dir]   (default mu-tilate/factory)
"""
import sys, wave, pathlib
import numpy as np

SR = 44100

def kick(n, f0=130.0, f1=48.0, decay=0.22):
    t = np.arange(n) / SR
    freq = f1 + (f0 - f1) * np.exp(-t * 28.0)           # pitch drops fast: the "thump"
    ph = 2 * np.pi * np.cumsum(freq) / SR
    return np.sin(ph) * np.exp(-t / decay)

def snare(n, rng, tone=190.0, decay=0.14):
    t = np.arange(n) / SR
    noise = rng.uniform(-1, 1, n) * np.exp(-t / decay)
    body = np.sin(2 * np.pi * tone * t) * np.exp(-t / 0.07)
    return 0.7 * noise + 0.5 * body

def hat(n, rng, decay=0.03):
    t = np.arange(n) / SR
    noise = rng.uniform(-1, 1, n)
    noise = np.diff(noise, prepend=0.0)                  # first difference = high-pass
    return noise * np.exp(-t / decay)

def clap(n, rng):
    t = np.arange(n) / SR
    env = sum(np.exp(-np.clip(t - d, 0, None) / 0.03) * (t >= d) for d in (0.0, 0.011, 0.022))
    return rng.uniform(-1, 1, n) * env * np.exp(-t / 0.12)

def render(bpm, pattern, seed, swing=0.0):
    """pattern: {voice: [(step16, gain)]} over 32 sixteenth-steps (2 bars)."""
    rng = np.random.default_rng(seed)
    step = 60.0 / bpm / 4
    length = int(round(32 * step * SR))
    out = np.zeros(length + SR)                          # tail room, folded back below
    voices = {
        'k': (kick, 0.6), 's': (lambda n: snare(n, rng), 0.5),
        'h': (lambda n: hat(n, rng), 0.7), 'o': (lambda n: hat(n, rng, 0.12), 0.7),
        'c': (lambda n: clap(n, rng), 0.5),
    }
    for v, hits in pattern.items():
        fn, dur = voices[v]
        for s, g in hits:
            off = step * s + (swing * step if s % 2 else 0.0)
            i = int(round(off * SR)); n = int(dur * SR)
            out[i:i + n] += g * fn(n)
    out[:SR] += out[length:length + SR]                  # wrap the tails so the loop is seamless
    out = out[:length]
    out = np.tanh(out * 1.2)
    return out / np.max(np.abs(out)) * 0.89              # about -1 dBFS

def save(path, x):
    pcm = np.clip(np.round(x * (2 ** 23 - 1)), -2 ** 23, 2 ** 23 - 1).astype('<i4')
    raw = pcm.view(np.uint8).reshape(-1, 4)[:, :3].tobytes()   # little-endian 24-bit
    with wave.open(str(path), 'wb') as w:
        w.setnchannels(1); w.setsampwidth(3); w.setframerate(SR); w.writeframes(raw)

def every(*steps, g=1.0): return [(s, g) for s in steps]
four = list(range(0, 32, 4))

LOOPS = {
    'Four On The Floor 124': (124, {'k': every(*four), 'c': every(4, 12, 20, 28),
                                    'h': every(*range(2, 32, 4), g=0.8), 'o': every(*range(2, 32, 4), g=0.0)}, 1, 0.0),
    'Boom Bap 90':           (90, {'k': every(0, 7, 10, 16, 23, 26), 's': every(4, 12, 20, 28),
                                   'h': every(*range(0, 32, 2), g=0.6)}, 2, 0.2),
    'Broken Beat 110':       (110, {'k': every(0, 3, 10, 16, 19, 25), 's': every(6, 14, 22, 30),
                                    'h': every(*range(0, 32, 2), g=0.55), 'o': every(15, 31, g=0.8)}, 3, 0.1),
    'Half Time 140':         (140, {'k': every(0, 10, 16), 's': every(8, 24),
                                    'h': every(*range(0, 32, 4), g=0.7)}, 4, 0.0),
    'Shuffle 100':           (100, {'k': every(0, 10, 16, 26), 's': every(8, 24),
                                    'h': every(*range(0, 32, 2), g=0.6)}, 5, 0.33),
    'Rolling Hats 128':      (128, {'k': every(*four), 's': every(8, 24),
                                    'h': every(*range(0, 32), g=0.45), 'o': every(*range(2, 32, 4), g=0.7)}, 6, 0.0),
}

def main():
    out = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else pathlib.Path(__file__).resolve().parent.parent / 'mu-tilate' / 'factory')
    out.mkdir(parents=True, exist_ok=True)
    for name, (bpm, pat, seed, swing) in LOOPS.items():
        f = out / f'{name}.wav'          # the BPM is the number in the file name
        save(f, render(bpm, pat, seed, swing))
        print(f.name, f.stat().st_size)

if __name__ == '__main__':
    main()
